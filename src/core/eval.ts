// Pawns before the river (Red's ranks 3 and 4): a central pawn is worth a little more.
const PAWN_HOME = [
  [32, 0, 34, 0, 38, 0, 34, 0, 32],
  [30, 0, 30, 0, 34, 0, 30, 0, 30],
];

/** Rough piece values by type, for move ordering and display (index = piece type). */
export const PIECE_VALUE = [0, 10000, 120, 120, 270, 600, 285, 40];

const TABLES = [null, KING_T, ADVISOR_T, ELEPHANT_T, HORSE_T, ROOK_T, CANNON_T, PAWN_T];

/** PST[piece][square]: value of a piece on a 16x16 mailbox square, for both sides. */
export const PST: Int16Array[] = Array.from({ length: 16 }, () => new Int16Array(256));

for (let type = 1; type <= 7; type++) {
  const table = TABLES[type]!;
  for (let y = 0; y < 10; y++) {
    for (let x = 0; x < 9; x++) {
      let v = table[9 - y][x];
      if (type === 7 && (y === 3 || y === 4)) v = PAWN_HOME[4 - y][x] || 30;
      if (type === 7 && y < 3) v = 30;
      // Red piece at (x, y); Black's table is mirrored top to bottom.
      PST[type][((y + 3) << 4) + x + 3] = v;
      PST[8 + type][((12 - y) << 4) + x + 3] = v;
    }
  }
}
